// Helper: Normalize lookup string
export function normalizeSearchTerm(term: string): string {
  return term
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9\s]/g, "")
    .replace(/\s+/g, " ");
}

// Full Search & Autocomplete across all 75 Villages and Hubs
export function searchKopargaonLocations(query: string) {
  if (!query || query.trim().length === 0) {
    return [
      ...TRANSIT_DESTINATION_NODES.slice(0, 3).map((h) => ({
        id: h.id,
        name: h.name,
        subtitle: `${h.taluka} Taluka • ${h.type.replace(/_/g, " ")}`,
        type: "HUB" as const,
        record: h,
      })),
      ...KOPARGAON_TALUKA_VILLAGES.slice(0, 7).map((v) => ({
        id: v.id,
        name: v.name,
        subtitle: `Kopargaon Taluka • ${v.has_verified_bus_stop ? "Verified Stop" : `Near ${v.nearest_verified_stop_name || "Route"}`}`,
        type: "VILLAGE" as const,
        record: v,
      })),
    ];
  }

  const normalized = normalizeSearchTerm(query);

  // Search Hubs
  const matchedHubs = TRANSIT_DESTINATION_NODES.filter((h) => {
    if (h.normalized_name.includes(normalized)) return true;
    return h.aliases.some((a) => normalizeSearchTerm(a).includes(normalized));
  }).map((h) => ({
    id: h.id,
    name: h.name,
    subtitle: `${h.taluka} Taluka • ${h.type.replace(/_/g, " ")}`,
    type: "HUB" as const,
    record: h,
  }));

  // Search Villages
  const matchedVillages = KOPARGAON_TALUKA_VILLAGES.filter((v) => {
    if (v.normalized_name.includes(normalized)) return true;
    return v.aliases.some((a) => normalizeSearchTerm(a).includes(normalized));
  }).map((v) => ({
    id: v.id,
    name: v.name,
    subtitle: `Kopargaon Taluka • ${v.has_verified_bus_stop ? "Served Bus Stop" : `Near ${v.nearest_verified_stop_name || "Route"} (${v.distance_to_nearest_stop_km}km)`}`,
    type: "VILLAGE" as const,
    record: v,
  }));

  return [...matchedHubs, ...matchedVillages];
}

// Find Village by ID or Alias
export function getVillageByIdOrName(idOrName: string): VillageRecord | undefined {
  const byId = KOPARGAON_TALUKA_VILLAGES.find((v) => v.id === idOrName);
  if (byId) return byId;

  const normalized = normalizeSearchTerm(idOrName);
  return KOPARGAON_TALUKA_VILLAGES.find(
    (v) => v.normalized_name === normalized || v.aliases.some((a) => normalizeSearchTerm(a) === normalized)
  );
}
